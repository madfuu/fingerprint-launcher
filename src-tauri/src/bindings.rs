//! TypeScript bindings of the bridge (implement.md P4): every type that crosses `invoke` or an
//! event, generated from its Rust definition into `src/lib/bindings/`, so `bridge.ts` never
//! restates a DTO by hand.
//!
//! `cargo test` regenerates the directory (writing only files whose content changed and
//! deleting stale ones); CI fails when the committed files differ from the output. Types derive
//! `ts_rs::TS` in test builds only, and their serde attributes (renames, `flatten`) shape the
//! output. Integers map to `number`: every integer on the bridge is far below 2^53.
//!
//! The output is not run through Prettier (the directory is in `.prettierignore`).
//!
//! ts-rs prints "failed to parse serde attribute ... deserialize_with" for
//! `SettingsPatch::user_data_root` while compiling tests: expected, the field's TypeScript type
//! comes from `ts(optional_fields)` instead.

