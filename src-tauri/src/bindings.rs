const OUT_DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/bindings");

const HEADER: &str = "// This file was generated by src-tauri/src/bindings.rs (cargo test). Do not edit it manually.\n";

/// Exports every root type; their dependencies come along.
fn export_roots(cfg: &Config) {
    fn export<T: TS + 'static>(cfg: &Config) {
        T::export_all(cfg)
            .unwrap_or_else(|err| panic!("export {}: {err}", std::any::type_name::<T>()));
    }
    export::<AppError>(cfg);
    // Profiles, groups, tags, proxies (and every type they embed).
    // `flatten` inlines these into the types that embed them, so they are roots of their own.
    export::<Profile>(cfg);
    export::<ProfileDraft>(cfg);
    export::<Page<ProfileRow>>(cfg);
    export::<ProfileQuery>(cfg);
    export::<GroupInput>(cfg);
    export::<TagInput>(cfg);
    export::<ProxyInput>(cfg);
    export::<PurgeResult>(cfg);
    export::<ImportResult>(cfg);
    // Kernels and command lines.
    export::<Kernel>(cfg);
    export::<KernelInput>(cfg);
    export::<KernelProbe>(cfg);
    export::<KernelCandidate>(cfg);
    export::<LaunchPlan>(cfg);
    export::<ArgSupport>(cfg);
    export::<FieldWarning>(cfg);
    // Browser lifecycle.
    export::<RunningInfo>(cfg);
    export::<StatusEvent>(cfg);
    export::<BatchProgress>(cfg);
    // Proxies, settings, app.
    export::<ProxyCheck>(cfg);
    export::<Settings>(cfg);
    export::<SettingsPatch>(cfg);
    export::<AppInfo>(cfg);
    export::<CloseRequested>(cfg);
}

/// Event names with their payload types (`events.rs`).
fn events_ts() -> String {
    format!(
        r#"{HEADER}import type {{ BatchProgress }} from "./BatchProgress";
import type {{ CloseRequested }} from "./CloseRequested";
import type {{ StatusEvent }} from "./StatusEvent";

/** Events the backend emits (design §5). */
export const EVENTS = {{
  profileStatusChanged: "{PROFILE_STATUS_CHANGED}",
  batchProgress: "{BATCH_PROGRESS}",
  appCloseRequested: "{APP_CLOSE_REQUESTED}",
}} as const;

/** Payload type of each event. */
export type EventPayloads = {{
  "{PROFILE_STATUS_CHANGED}": StatusEvent;
  "{BATCH_PROGRESS}": BatchProgress;
  "{APP_CLOSE_REQUESTED}": CloseRequested;
}};
"#
    )
}

/// Re-exports every generated module.
fn index_ts(files: &BTreeMap<String, String>) -> String {
    let mut index = String::from(HEADER);
    for name in files.keys() {
        let module = name.trim_end_matches(".ts");
        if module == "events" {
            index.push_str("export * from \"./events\";\n");
        } else {
            index.push_str(&format!("export type * from \"./{module}\";\n"));
        }
    }
    index
}

#[test]
fn export_bindings() {
    let temp = tempfile::tempdir().unwrap();
    let cfg = Config::new()
        .with_out_dir(temp.path())
        .with_large_int("number");
    export_roots(&cfg);

    let mut files = BTreeMap::new();
    for entry in std::fs::read_dir(temp.path()).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_str().unwrap().to_owned();
        assert!(
            path.is_file() && name.ends_with(".ts"),
            "unexpected output {name}"
        );
        files.insert(name, std::fs::read_to_string(&path).unwrap());
    }
    files.insert("events.ts".to_owned(), events_ts());
    let index = index_ts(&files);
    files.insert("index.ts".to_owned(), index);

    sync_dir(Path::new(OUT_DIR), &files);
}

/// Makes `dir` hold exactly `files` (`*.ts` only), rewriting only what changed.
fn sync_dir(dir: &Path, files: &BTreeMap<String, String>) {
    std::fs::create_dir_all(dir).unwrap();
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy().into_owned();
        if name.ends_with(".ts") && !files.contains_key(&name) {
            std::fs::remove_file(&path).unwrap();
        }
    }
    for (name, content) in files {
        let path = dir.join(name);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
            std::fs::write(&path, content).unwrap();
        }
    }
}
